#!/usr/bin/env node
/**
 * Generates 100 placeholder PNG backgrounds + static require barrel for Metro.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = join(root, "assets", "onboarding");
const barrelPath = join(root, "src", "data", "audioOnboardingImages.ts");

mkdirSync(assetsDir, { recursive: true });

const VARIANTS = [
  [10, 16, 29],
  [18, 26, 46],
  [34, 211, 153],
];

function crc32(buf) {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) {
    crc ^= buf[i];
    for (let j = 0; j < 8; j += 1) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const typeBuf = Buffer.from(type, "ascii");
  const lenBuf = Buffer.alloc(4);
  lenBuf.writeUInt32BE(data.length, 0);
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([lenBuf, typeBuf, data, crcBuf]);
}

function createSolidPng(width, height, r, g, b) {
  const row = Buffer.alloc(1 + width * 3);
  row[0] = 0;
  for (let x = 0; x < width; x += 1) {
    const offset = 1 + x * 3;
    row[offset] = r;
    row[offset + 1] = g;
    row[offset + 2] = b;
  }
  const raw = Buffer.concat(Array.from({ length: height }, () => row));
  const compressed = deflateSync(raw);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", ihdr),
    pngChunk("IDAT", compressed),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

const requires = [];

for (let i = 1; i <= 100; i += 1) {
  const id = String(i).padStart(3, "0");
  const variant = VARIANTS[(i - 1) % VARIANTS.length];
  const png = createSolidPng(360, 640, ...variant);
  const fileName = `slide-${id}.png`;
  writeFileSync(join(assetsDir, fileName), png);
  requires.push(`  require("../../assets/onboarding/${fileName}"),`);
}

const barrel = `/** Auto-generated by scripts/generate-onboarding-slides.mjs — do not edit manually. */
import type { ImageSourcePropType } from "react-native";

export const AUDIO_ONBOARDING_IMAGES: readonly ImageSourcePropType[] = [
${requires.join("\n")}
] as const;
`;

writeFileSync(barrelPath, barrel);
console.log(`Generated 100 onboarding PNGs in assets/onboarding/ and ${barrelPath}`);
